#!/usr/bin/env node
// Regenerates mods/files-transfer/icons/ and mods/files-transfer/icons.js from the
// material-icon-theme npm package (MIT, https://github.com/material-extensions/vscode-material-icon-theme).
//
//   node tools/build-icons.mjs [version]     default: the version pinned below
//
// Needs node, npm and tar. Writes only inside mods/files-transfer/.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync, rmSync, mkdirSync, copyFileSync, readdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const VERSION = process.argv[2] ?? "5.40.0";
const MOD = join(dirname(fileURLToPath(import.meta.url)), "..", "mods", "file-icons");
const ICONS = join(MOD, "icons");

const tmp = mkdtempSync(join(tmpdir(), "files-transfer-"));
try {
  const tgz = execFileSync("npm", ["pack", `material-icon-theme@${VERSION}`, "--silent"], { cwd: tmp, encoding: "utf8" }).trim().split("\n").pop();
  execFileSync("tar", ["xzf", tgz], { cwd: tmp });
  const pkg = join(tmp, "package");
  const manifest = JSON.parse(readFileSync(join(pkg, "dist", "material-icons.json"), "utf8"));
  const defs = manifest.iconDefinitions;

  // VS Code matches names case-insensitively; the manifest has no case-only collisions.
  const lower = (map = {}) => Object.fromEntries(Object.entries(map).map(([k, v]) => [k.toLowerCase(), v]));

  // Folder keys come in five spellings (src, .src, _src, -src, __src__). Keep the bare one and
  // only those spellings the mod's own normalisation (see main.js `bare`) would get wrong.
  const bare = name => name.replace(/^__(.+)__$/, "$1").replace(/^[._-]/, "");
  function folders(map = {}) {
    const all = lower(map), out = {};
    for (const [k, v] of Object.entries(all)) if (bare(k) === k) out[k] = v;
    for (const [k, v] of Object.entries(all)) if ((out[k] ?? out[bare(k)]) !== v) out[k] = v;
    return out;
  }

  const light = manifest.light ?? {};
  const data = {
    file: manifest.file,
    folder: manifest.folder,
    fileNames: lower(manifest.fileNames),
    fileExtensions: lower(manifest.fileExtensions),
    folderNames: folders(manifest.folderNames),
    light: {
      fileNames: lower(light.fileNames),
      fileExtensions: lower(light.fileExtensions),
      folderNames: folders(light.folderNames),
    },
  };

  // Every icon the tables can name, with its expanded folder twin.
  const open = id => id.endsWith("_light") ? `${id.slice(0, -6)}-open_light` : `${id}-open`;
  const used = new Set([data.file, data.folder, open(data.folder)]);
  for (const table of [data, data.light]) {
    for (const id of Object.values(table.fileNames)) used.add(id);
    for (const id of Object.values(table.fileExtensions)) used.add(id);
    for (const id of Object.values(table.folderNames)) { used.add(id); used.add(open(id)); }
  }
  const missing = [...used].filter(id => !defs[id]);
  if (missing.length) throw new Error(`manifest names icons it does not define: ${missing.join(", ")}`);

  rmSync(ICONS, { recursive: true, force: true });
  mkdirSync(ICONS, { recursive: true });
  for (const id of [...used].sort()) copyFileSync(join(pkg, "dist", defs[id].iconPath), join(ICONS, `${id}.svg`));
  copyFileSync(join(pkg, "LICENSE"), join(MOD, "LICENSE-material-icon-theme.txt"));

  writeFileSync(join(MOD, "icons.js"),
    `// Generated by tools/build-icons.mjs from material-icon-theme ${VERSION} (MIT). Do not edit.\n` +
    `export default ${JSON.stringify(data)};\n`);
  console.log(`material-icon-theme ${VERSION}: ${readdirSync(ICONS).length} icons, ` +
    `${Object.keys(data.fileNames).length} file names, ${Object.keys(data.fileExtensions).length} extensions, ` +
    `${Object.keys(data.folderNames).length} folder names → ${basename(MOD)}/`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
