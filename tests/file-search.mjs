import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read = name => fs.readFileSync(`mods/files-workspace/${name}.js`, 'utf8').replace(/^import .*;$/gm, '').replaceAll('export default class', 'class').replaceAll('export async function', 'async function').replaceAll('export const', 'const').replaceAll('export function', 'function');
let gitResult={code:0,stdout:'docs/a.md\0docs/a.md\0한글.md\0'};
const file = vm.runInNewContext(read('file-search')+'\n({searchPaths,filterPaths})', {exec:async()=>gitResult});
let result = await file.searchPaths('/repo',null,()=>false);
assert.deepEqual(Array.from(result.paths),['docs/a.md','한글.md']);
assert.deepEqual(Array.from(file.filterPaths(result.paths,'DOCS\\A')),['docs/a.md']);
assert.equal(await file.searchPaths('/repo',null,()=>true),null);
assert.deepEqual(Array.from(file.filterPaths(['docs/a.md','docs/b.txt','x.MD'], '*.md')), ['docs/a.md','x.MD']);
assert.deepEqual(Array.from(file.filterPaths(['docs/a.md','src/a.md'], 'docs/*.md')), ['docs/a.md']);
assert.deepEqual(Array.from(file.filterPaths(['a[1].md','ab.md'], 'a[?].md')), ['a[1].md']);
gitResult={code:1};
result=await file.searchPaths('/repo',null,()=>false);
assert.equal(result.paths.length,0); assert.match(result.note,/Git folder/);
console.log('PASS Git path search, literal and wildcard queries, cancellation and no recursive fallback');
